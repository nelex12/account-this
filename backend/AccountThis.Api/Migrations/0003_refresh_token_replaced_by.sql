-- ---------- REFRESH TOKEN: какой токен выдан взамен ----------
-- Ротация (POST /api/auth/refresh) гасит предъявленный токен и записывает сюда id выданного взамен.
-- Нужно, чтобы отличить потерянный ответ от кражи: сервер выдал новый токен, но ответ до браузера не дошёл
-- (F5 сразу после открытия страницы, обрыв сети), и браузер снова предъявляет старый. Если выданный взамен
-- токен ещё ни разу не использован и с ротации прошло не больше короткого окна (AuthService.RefreshReuseGrace),
-- это повтор того же клиента, а не кража: сессия продолжается. Иначе — как раньше, гасится вся сессия.
-- NULL — токен не погашен или погашен не ротацией (выход, увольнение, смена пароля, повтор, потерянный ответ).

ALTER TABLE refresh_tokens ADD COLUMN replaced_by BIGINT REFERENCES refresh_tokens(id);
